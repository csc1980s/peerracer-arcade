#!/usr/bin/env python3
"""
Audio Manifest Generator
Creates JSON manifest files listing all generated audio for easy loading in game
"""

import json
from pathlib import Path

def create_manifest():
    """Create manifest.json files for each voice directory"""

    base_dir = Path(__file__).parent / 'encouragement'

    if not base_dir.exists():
        print(f"ERROR: ERROR: Audio directory not found: {base_dir}")
        print("Please generate audio files first using generate_multi_voice_audio.py")
        return

    # Master manifest
    master_manifest = {
        "version": "1.0",
        "description": "Victorian Christmas Solitaire Audio Files",
        "voices": {}
    }

    # Process each voice directory
    for voice_dir in base_dir.iterdir():
        if not voice_dir.is_dir():
            continue

        voice_name = voice_dir.name
        print(f"\nProcessing Processing {voice_name}/ directory...")

        # Find all mp3 files
        audio_files = sorted(voice_dir.glob('*.mp3'))

        if not audio_files:
            print(f"  WARNING:  No audio files found in {voice_name}/")
            continue

        # Create voice manifest
        voice_manifest = {
            "voice": voice_name,
            "fileCount": len(audio_files),
            "files": []
        }

        # Process each audio file
        for audio_file in audio_files:
            filename = audio_file.name
            file_info = {
                "filename": filename,
                "path": f"audio/encouragement/{voice_name}/{filename}",
                "relativePath": f"encouragement/{voice_name}/{filename}"
            }

            # Parse filename to extract metadata
            # Format: suitname_quote_###_voicetype.mp3
            # Example: hearts_quote_001_king.mp3
            parts = filename.replace('.mp3', '').split('_')

            if len(parts) >= 3:
                if parts[0] == 'general':
                    file_info["category"] = "general"
                    file_info["quoteNumber"] = parts[2]
                else:
                    file_info["suit"] = parts[0]
                    file_info["category"] = "suit"
                    file_info["quoteNumber"] = parts[2]

            voice_manifest["files"].append(file_info)

        # Save voice-specific manifest
        manifest_file = voice_dir / 'manifest.json'
        with open(manifest_file, 'w', encoding='utf-8') as f:
            json.dump(voice_manifest, f, indent=2)

        print(f"  OK Created manifest.json ({len(audio_files)} files)")

        # Add to master manifest
        master_manifest["voices"][voice_name] = {
            "fileCount": len(audio_files),
            "manifestPath": f"audio/encouragement/{voice_name}/manifest.json"
        }

    # Save master manifest
    master_file = base_dir / 'master_manifest.json'
    with open(master_file, 'w', encoding='utf-8') as f:
        json.dump(master_manifest, f, indent=2)

    print(f"\nSUCCESS: Master manifest created: {master_file}")

    # Create index file for web loading
    create_web_index(base_dir, master_manifest)

    # Print summary
    print_summary(master_manifest)

def create_web_index(base_dir, master_manifest):
    """Create index.js file for easy web integration"""

    js_content = """// Victorian Christmas Solitaire - Audio Index
// Auto-generated by create_audio_manifest.py

const AudioLibrary = {
  baseDir: 'audio/encouragement/',

  voices: {
"""

    for voice_name, voice_info in master_manifest["voices"].items():
        js_content += f"    {voice_name}: '{voice_info['manifestPath']}',\n"

    js_content += """  },

  async loadVoice(voiceName) {
    const manifestPath = this.voices[voiceName];
    if (!manifestPath) {
      throw new Error(`Unknown voice: ${voiceName}`);
    }

    const response = await fetch(manifestPath);
    const manifest = await response.json();
    return manifest.files;
  },

  async loadAll() {
    const allAudio = {};

    for (const [voiceName, manifestPath] of Object.entries(this.voices)) {
      const files = await this.loadVoice(voiceName);
      allAudio[voiceName] = files;
    }

    return allAudio;
  },

  selectRandomQuote(voiceName, suit = null) {
    const files = this.audioFiles[voiceName];
    if (!files) return null;

    // Filter by suit if specified
    let candidates = suit
      ? files.filter(f => f.suit === suit)
      : files;

    if (candidates.length === 0) {
      candidates = files; // Fallback to all files
    }

    // Select random
    const randomIndex = Math.floor(Math.random() * candidates.length);
    return candidates[randomIndex].path;
  }
};

// Export for use in game
if (typeof module !== 'undefined' && module.exports) {
  module.exports = AudioLibrary;
}
"""

    index_file = base_dir / 'index.js'
    with open(index_file, 'w', encoding='utf-8') as f:
        f.write(js_content)

    print(f"  OK Created index.js for web integration")

def print_summary(master_manifest):
    """Print generation summary"""
    print("\n" + "="*60)
    print("  MANIFEST GENERATION COMPLETE")
    print("="*60)

    total_files = sum(v["fileCount"] for v in master_manifest["voices"].values())

    print(f"\nTotal audio files: {total_files}")
    print("\nBy voice:")
    for voice_name, voice_info in master_manifest["voices"].items():
        print(f"  {voice_name}: {voice_info['fileCount']} files")

    print("\nGenerated files:")
    print("  - encouragement/master_manifest.json (master index)")
    print("  - encouragement/index.js (web integration)")
    print("  - encouragement/[voice]/manifest.json (per-voice manifests)")

    print("\nUsage in game:")
    print("  JavaScript:")
    print("    import AudioLibrary from './audio/encouragement/index.js';")
    print("    const audioFiles = await AudioLibrary.loadAll();")
    print()

if __name__ == "__main__":
    print("""
==============================================================
  Audio Manifest Generator
  Victorian Christmas Solitaire
==============================================================
    """)

    create_manifest()
